"""Phase 3: the Mathematical Core - trained XGBoost model, SHAP explainer,
and upcoming-fixture predictor.

This package's shared helpers (paths, dataset loading, the chronological
validation protocol) live here so tune/train/evaluate/explain/predict all
agree on exactly how data is split and prepared - the single source of
truth that keeps tuning, training, and inference consistent.
"""

import os
import tempfile
from pathlib import Path

# Ensure matplotlib/shap have a writable cache dir before they are imported
# anywhere in this package (avoids noise when HOME is not writable).
os.environ.setdefault("MPLCONFIGDIR", os.path.join(tempfile.gettempdir(), "mplconfig"))

import pandas as pd

from feature_engineering.build_dataset import DATASET_PATH, ID_COLUMNS, LABEL_COLUMN

ENGINE_ROOT = Path(__file__).resolve().parents[1]
MODELS_DIR = ENGINE_ROOT / "models"

# Artifact paths (all gitignored; regenerated by train.py).
MODEL_PATH = MODELS_DIR / "model.ubj"
CALIBRATOR_PATH = MODELS_DIR / "calibrator.pkl"
BEST_PARAMS_PATH = MODELS_DIR / "best_params.json"
FEATURE_COLUMNS_PATH = MODELS_DIR / "feature_columns.json"
METRICS_PATH = MODELS_DIR / "metrics.json"

# Validation protocol.
#   - 2025-2026 is the final holdout, never seen during tuning or calibration.
#   - Tuning/calibration use expanding-window folds inside 2015-2024:
#     train through season S, validate on S+1.
HOLDOUT_START_SEASON = 2025
EXPANDING_WINDOW_VAL_SEASONS = (2021, 2022, 2023, 2024)


def load_dataset() -> pd.DataFrame:
    """Load the training dataset with the categorical dtype XGBoost expects."""
    df = pd.read_parquet(DATASET_PATH)
    df["ctx_weather"] = df["ctx_weather"].astype("category")
    return df


def get_feature_columns(df: pd.DataFrame) -> list[str]:
    """Ordered model-input columns (everything except identifiers and label)."""
    return [c for c in df.columns if c not in ID_COLUMNS + [LABEL_COLUMN]]


def development_split(df: pd.DataFrame):
    """Split into development (<=2024, for tuning/calibration) and holdout."""
    dev = df[df["season"] < HOLDOUT_START_SEASON].reset_index(drop=True)
    holdout = df[df["season"] >= HOLDOUT_START_SEASON].reset_index(drop=True)
    return dev, holdout


def expanding_window_folds(dev: pd.DataFrame):
    """Yield (train_idx, val_idx) for each expanding-window validation fold.

    Fold k trains on every season strictly before val_season and validates
    on val_season - mirroring how the model is used in production (predict
    the next season/round from everything before it).
    """
    for val_season in EXPANDING_WINDOW_VAL_SEASONS:
        train_idx = dev.index[dev["season"] < val_season].to_numpy()
        val_idx = dev.index[dev["season"] == val_season].to_numpy()
        if len(val_idx) and len(train_idx):
            yield val_season, train_idx, val_idx
